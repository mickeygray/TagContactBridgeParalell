const ACTIVITY_REVIEW_REVIEW_TYPE = "contact-safety";

// activityAiReviewService.js buildUserPrompt(domain, caseId, activities).
// activitiesText = the pre-formatted activity block (see rules.formatActivities).
function buildActivityReviewUser({ domain, caseId, activitiesText }) {
  return [
    `Domain: ${domain}`,
    `Case ID: ${caseId}`,
    `Review type: ${ACTIVITY_REVIEW_REVIEW_TYPE}`,
    "Task: Determine whether future contact should continue based on the activities below.",
    "If the notes show strong negative consent or legal risk, prefer stop_contact.",
    "If the notes are mixed or unclear, prefer manual_review.",
    "Activities:",
    activitiesText,
  ].join("\n\n");
}

